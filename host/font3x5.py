def text_columns(text):
    """Return the text as a list of pixel columns, each a list of 5 booleans (top to bottom)."""
    plain = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().upper()
    columns = []
    for char in plain:
        glyph = GLYPHS.get(char, GLYPHS["?"])
        for x in range(3):
            columns.append([glyph[y][x] == "#" for y in range(5)])
        columns.append([False] * 5)
    return columns
